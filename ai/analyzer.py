def stream_goonghap(person1: dict, person2: dict, relation_type: str = '연인'):
    """궁합 분석 스트리밍 — max_tokens 초과 시 자동 이어쓰기"""
    saju1_json = json.dumps(person1.get('saju', {}), ensure_ascii=False, indent=2)
    saju2_json = json.dumps(person2.get('saju', {}), ensure_ascii=False, indent=2)

    rel_ctx = _get_relation_context(relation_type)
    user_prompt = GOONGHAP_PROMPT.format(
        name1=person1.get('name', '1번'),
        saju1_json=saju1_json,
        name2=person2.get('name', '2번'),
        saju2_json=saju2_json,
        relation_type=relation_type,
        relation_intro=rel_ctx['intro'],
        sinshin_context=rel_ctx['sinshin'],
        scoring_guide=rel_ctx['scoring'],
        relation_type_ko=relation_type,
    )
    system_prompt = "당신은 20년 경력의 전문 사주 컨설턴트입니다. 정확하고 실용적인 궁합 분석을 제공합니다. 반드시 7개 항목을 모두 완성하여 종합 점수와 최종 의견까지 작성하세요."

    yield "data: {\"type\":\"start\"}\n\n"
    try:
        messages = [{"role": "user", "content": user_prompt}]
        accumulated = ""
        max_rounds = 5  # 최대 이어쓰기 횟수 (무한루프 방지)

        for round_num in range(max_rounds):
            stop_reason = None
            round_text = ""

            with client.messages.stream(
                model="claude-sonnet-4-6",
                max_tokens=8000,
                messages=messages,
                system=system_prompt,
            ) as stream:
                for text in stream.text_stream:
                    round_text += text
                    escaped = text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\r', '')
                    yield f"data: {{\"type\":\"text\",\"text\":\"{escaped}\"}}\n\n"
                # 스트림 종료 후 stop_reason 확인
                final_msg = stream.get_final_message()
                stop_reason = final_msg.stop_reason

            accumulated += round_text

            # 정상 종료 또는 이어쓰기 불필요
            if stop_reason != "max_tokens":
                break

            # max_tokens로 잘렸으면 → 이어쓰기 요청
            messages = [
                {"role": "user", "content": user_prompt},
                {"role": "assistant", "content": accumulated},
                {"role": "user", "content": "중단된 부분부터 이어서 계속 작성해주세요. 앞 내용을 반복하지 말고 바로 이어서 쓰세요."},
            ]

    except Exception as e:
        yield f"data: {{\"type\":\"error\",\"message\":\"{str(e)}\"}}\n\n"

    yield "data: {\"type\":\"done\"}\n\n"
